// Writes device/test-vectors.json from the TypeScript implementation. The
// gateway tests and the firmware's native test build both check against it.
//
//   node scripts/gen-vectors.ts

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { sha256 } from "@noble/hashes/sha2.js";
import { secp256k1 } from "@noble/curves/secp256k1.js";
import { bytesToHex, keccak256, stringToBytes, type Address, type Hex } from "viem";
import { batchDigest, popDigest } from "../lib/digest.ts";
import {
  ecdsaAddress, ecdsaSignDigest, largeLiftCount, mldsaKeygen, mldsaSign, seedCommitment, wrapSeed,
} from "../lib/keys.ts";
import { merkleProof, merkleRoot } from "../lib/merkle.ts";
import { encodeReading, readingLeaf, toWireHex, type Reading } from "../lib/reading.ts";
import { readingFromIoreg } from "../gateway/src/ioreg.ts";

const here = dirname(fileURLToPath(import.meta.url));
const deviceDir = resolve(here, "..");
const fx = JSON.parse(readFileSync(resolve(deviceDir, "../contracts/test/fixtures/mldsa.json"), "utf8"));

const seed = (label: string) => sha256(stringToBytes(`kutle-vector:${label}`));

const T0 = 1_800_000_000;
const mac = readingFromIoreg(readFileSync(resolve(deviceDir, "gateway/test/fixtures/ioreg-apple-smart-battery.plist"), "utf8"), T0);

const readings: Reading[] = [
  mac,
  { ...mac, timestamp: T0 + 60, current_mA: -2150, temperature_centiC: -1050, stateOfCharge_pct: 0, cellVoltage_mV: [3001, 2999, 3010] },
  {
    timestamp: T0 + 120, cycleCount: 0xffff_ffff, designCapacity_mAh: 0xffff_ffff, fullChargeCapacity_mAh: 0xffff_ffff,
    packVoltage_mV: 0xffff_ffff, current_mA: -0x8000_0000, temperature_centiC: -0x8000, stateOfCharge_pct: 100,
    cellVoltage_mV: [0xffff, 0xffff, 0xffff], cellQmax_mAh: [0xffff, 0xffff, 0xffff], cellResistance: [0xffff, 0xffff, 0xffff],
  },
  {
    timestamp: T0 + 180, cycleCount: 0, designCapacity_mAh: 0, fullChargeCapacity_mAh: 0, packVoltage_mV: 0,
    current_mA: 0x7fff_ffff, temperature_centiC: 0x7fff, stateOfCharge_pct: 0,
    cellVoltage_mV: [0, 0, 0], cellQmax_mAh: [0, 0, 0], cellResistance: [0, 0, 0],
  },
  { ...mac, timestamp: T0 + 240, current_mA: 1, temperature_centiC: -1 },
  { ...mac, timestamp: T0 + 300, cellVoltage_mV: [3840, 3851, 0], cellQmax_mAh: [4805, 4810, 0], cellResistance: [55, 61, 0] },
  { ...mac, timestamp: T0 + 300 },
];

const leaves = readings.map(readingLeaf);

const trees = [1, 2, 3, 4, 5, 6, 7].map((n) => {
  const l = leaves.slice(0, n);
  return { n, root: merkleRoot(l), proofs: l.map((_, i) => merkleProof(l, i)) };
});

const READING_LOG = fx.readingLog as Address;
const REGISTRY = fx.registry as Address;
const DEVICE = fx.deviceA as Hex;

// Keys derived from fixed seeds so both implementations derive the same thing.
const xi = seed("xi");
const ecdsaKey = bytesToHex(seed("ecdsa"));
const { publicKey, secretKey } = mldsaKeygen(xi);
const address = ecdsaAddress(ecdsaKey);
const pkHash = keccak256(publicKey);

const batches = [
  { chainId: 31337n, readingLog: READING_LOG, passportId: 1n, seq: 0n, n: 7 },
  { chainId: 11155111n, readingLog: "0x00000000000000000000000000000000deadbeef" as Address, passportId: (1n << 255n) + 3n, seq: 4294967296n, n: 3 },
];
const batchVectors = [];
for (const b of batches) {
  const sub = readings.slice(0, b.n);
  const root = merkleRoot(sub.map(readingLeaf));
  const header = {
    deviceId: DEVICE, passportId: b.passportId, seq: b.seq, root,
    fromTs: BigInt(sub[0].timestamp), toTs: BigInt(sub[sub.length - 1].timestamp), count: sub.length,
  };
  const digest = batchDigest(b.chainId, b.readingLog, header);
  batchVectors.push({
    chainId: b.chainId.toString(), readingLog: b.readingLog, deviceId: DEVICE, passportId: b.passportId.toString(),
    seq: b.seq.toString(), readings: b.n, root, fromTs: header.fromTs.toString(), toTs: header.toTs.toString(),
    count: header.count, digest,
    ecdsaSig: await ecdsaSignDigest(ecdsaKey, digest),
    mldsaSig: mldsaSign(digest, secretKey),
  });
}

const popVectors = [
  // Must reproduce the digest in contracts/test/fixtures/mldsa.json.
  { chainId: "31337", registry: REGISTRY, deviceId: DEVICE, version: 1, ecdsaSigner: fx.keyA1.ecdsaSigner, pkHash: fx.keyA1.pkHash, digest: fx.keyA1.popDigest },
  { chainId: "31337", registry: REGISTRY, deviceId: DEVICE, version: 7, ecdsaSigner: address, pkHash, digest: popDigest(31337n, REGISTRY, DEVICE, 7, address, pkHash) },
];
if (popDigest(31337n, REGISTRY, DEVICE, 1, fx.keyA1.ecdsaSigner, fx.keyA1.pkHash) !== fx.keyA1.popDigest) {
  throw new Error("popDigest no longer matches the contract fixture");
}

const stationSecret = seed("station");
const ephemeral = seed("ephemeral");
const w = wrapSeed(xi, ephemeral, secp256k1.getPublicKey(stationSecret, true), address);

const out = {
  note: "Generated by device/scripts/gen-vectors.ts from the TypeScript implementation. Do not edit by hand.",
  spec: "device/SPEC.md v1",
  readings: readings.map((r, i) => ({ reading: r, wire: toWireHex(r), encoded: encodeReading(r), leaf: leaves[i] })),
  trees,
  batches: batchVectors,
  pops: popVectors,
  keys: {
    xi: bytesToHex(xi),
    ecdsaKey,
    address,
    pk: bytesToHex(publicKey),
    pkHash,
    commitment: seedCommitment(xi),
    largeLiftCount: largeLiftCount(publicKey),
  },
  wrap: {
    stationSecret: bytesToHex(stationSecret),
    stationPub: bytesToHex(secp256k1.getPublicKey(stationSecret, true)),
    ephemeralSecret: bytesToHex(ephemeral),
    deviceAddress: address,
    xi: bytesToHex(xi),
    E: bytesToHex(w.E),
    ct: bytesToHex(w.ct),
    tag: bytesToHex(w.tag),
  },
};

writeFileSync(resolve(deviceDir, "test-vectors.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${resolve(deviceDir, "test-vectors.json")}`);
