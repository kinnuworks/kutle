// Generates the ML-DSA-44 keys, prepared verifier blobs and signatures that the
// Foundry tests use. Tests may not shell out (ffi is off), so everything a test
// needs is computed here once and committed as JSON.
//
// The digests below must match DeviceRegistry.popDigest and
// ReadingLog.batchDigest byte for byte. Tests deploy those contracts at the fixed
// addresses below on chain id 31337 so the digests are reproducible.
//
//   node fixtures/gen.mjs

import { ml_dsa44 } from "@noble/post-quantum/ml-dsa.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { encodeAbiParameters, keccak256, toHex, hexToBytes, stringToHex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { prepareBlob } from "./prepare.mjs";
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = resolve(here, "../../contracts");
const outDir = resolve(contracts, "test/fixtures");

export const CHAIN_ID = 31337n;
export const REGISTRY = "0x00000000000000000000000000000000000d3c1e";
export const READING_LOG = "0x000000000000000000000000000000000000106e";

const seed = (label) => sha256(new TextEncoder().encode(`kutle-fixture:${label}`));
const ecdsaKey = (label) => toHex(seed(`ecdsa:${label}`));

const prepare = (pk) => toHex(prepareBlob(pk));

function popDigest(deviceId, version, ecdsaSigner, pkHash) {
  return keccak256(
    encodeAbiParameters(
      [
        { type: "bytes32" }, { type: "uint256" }, { type: "address" }, { type: "bytes32" },
        { type: "uint32" }, { type: "address" }, { type: "bytes32" },
      ],
      [keccak256(stringToHex("KUTLE_DEVICE_POP_V1")), CHAIN_ID, REGISTRY, deviceId, version, ecdsaSigner, pkHash],
    ),
  );
}

const BATCH_TYPEHASH = keccak256(
  stringToHex(
    "KutleReadingBatch(bytes32 deviceId,uint256 passportId,uint64 seq,bytes32 root,uint64 fromTs,uint64 toTs,uint32 count)",
  ),
);

function batchDigest(b) {
  return keccak256(
    encodeAbiParameters(
      [
        { type: "bytes32" }, { type: "uint256" }, { type: "address" }, { type: "bytes32" }, { type: "uint256" },
        { type: "uint64" }, { type: "bytes32" }, { type: "uint64" }, { type: "uint64" }, { type: "uint32" },
      ],
      [BATCH_TYPEHASH, CHAIN_ID, READING_LOG, b.deviceId, b.passportId, b.seq, b.root, b.fromTs, b.toTs, b.count],
    ),
  );
}

async function makeKey(label, deviceId, version) {
  const { publicKey, secretKey } = ml_dsa44.keygen(seed(`mldsa:${label}`));
  const account = privateKeyToAccount(ecdsaKey(label));
  const pkHash = keccak256(publicKey);
  const digest = popDigest(deviceId, version, account.address, pkHash);
  const popMldsa = toHex(ml_dsa44.sign(hexToBytes(digest), secretKey));
  const popEcdsa = await account.signMessage({ message: { raw: digest } });
  return {
    label, version, ecdsaPrivateKey: ecdsaKey(label), ecdsaSigner: account.address,
    pk: toHex(publicKey), pkHash, blob: prepare(publicKey), popDigest: digest, popMldsa, popEcdsa,
    secretKey,
  };
}

async function signBatch(key, b) {
  const digest = batchDigest(b);
  const account = privateKeyToAccount(key.ecdsaPrivateKey);
  return {
    ...Object.fromEntries(Object.entries(b).map(([k, v]) => [k, typeof v === "bigint" ? v.toString() : v])),
    digest,
    ecdsaSig: await account.signMessage({ message: { raw: digest } }),
    mldsaSig: toHex(ml_dsa44.sign(hexToBytes(digest), key.secretKey)),
  };
}

// A key whose t1 is all zeros: forgeable without a secret, must be refused.
function degenerateKey() {
  const pk = new Uint8Array(1312);
  pk.set(seed("degenerate-rho"), 0);
  return toHex(pk);
}

const T0 = 1_800_000_000n;
const deviceA = keccak256(stringToHex("kutle-demo-device-A"));
const deviceB = keccak256(stringToHex("kutle-demo-device-B"));

const keyA1 = await makeKey("deviceA-v1", deviceA, 1);
const keyA2 = await makeKey("deviceA-v2", deviceA, 2);
const keyB1 = await makeKey("deviceB-v1", deviceB, 1);

const root = (n) => keccak256(stringToHex(`readings-root-${n}`));
const batches = [
  await signBatch(keyA1, { deviceId: deviceA, passportId: 1n, seq: 0n, root: root(0), fromTs: T0 - 3600n, toTs: T0 - 1800n, count: 60 }),
  await signBatch(keyA1, { deviceId: deviceA, passportId: 1n, seq: 1n, root: root(1), fromTs: T0 - 1800n, toTs: T0, count: 60 }),
  await signBatch(keyA2, { deviceId: deviceA, passportId: 1n, seq: 2n, root: root(2), fromTs: T0, toTs: T0 + 600n, count: 20 }),
];

const strip = ({ secretKey, ...rest }) => rest;
const out = {
  note: "Generated by tools/fixtures/gen.mjs. Do not edit by hand.",
  chainId: CHAIN_ID.toString(),
  registry: REGISTRY,
  readingLog: READING_LOG,
  t0: T0.toString(),
  deviceA,
  deviceB,
  keyA1: strip(keyA1),
  keyA2: strip(keyA2),
  keyB1: strip(keyB1),
  degeneratePk: degenerateKey(),
  batches,
};

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "mldsa.json"), JSON.stringify(out, null, 2) + "\n");
const helper = readFileSync(resolve(contracts, "lib/evm-ml-dsa-verifier/helpers/f1600_170.hex"), "utf8").trim();
writeFileSync(resolve(outDir, "f1600_170.hex"), (helper.startsWith("0x") ? helper : "0x" + helper));
console.log(`wrote ${resolve(outDir, "mldsa.json")}`);
