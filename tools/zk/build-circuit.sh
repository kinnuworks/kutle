#!/usr/bin/env bash
# Compile circuits/shielded_spend, run its tests, and regenerate
# contracts/src/verifiers/ShieldedSpendVerifier.sol.
#
# Toolchain (a pair listed in bbup's bb-versions.json):
#   noirup -v 1.0.0-beta.22
#   bbup   -v 5.0.0-nightly.20260522
#
# Two edits are applied to bb's output, both mechanical:
#  1. The contract is renamed HonkVerifier -> ShieldedSpendVerifier.
#  2. Its five inline assembly blocks are marked ("memory-safe"). Each one only
#     writes at or past the free memory pointer, or in the 0x00-0x3f scratch
#     space, so the annotation is accurate. Without it solc 0.8.30 with via_ir
#     (the project setting) cannot move locals to memory and stops with
#     "stack too deep". bb's --optimized flavour hits a Yul stack layout
#     assertion under the same settings, so the plain flavour is used.
set -euo pipefail

export PATH="$HOME/.nargo/bin:$HOME/.bb:$PATH"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
CIRCUIT="$ROOT/circuits/shielded_spend"
OUT="$ROOT/contracts/src/verifiers/ShieldedSpendVerifier.sol"

cd "$CIRCUIT"
nargo test
nargo compile
bb gates -b target/shielded_spend.json
bb write_vk -b target/shielded_spend.json -o target -t evm
bb write_solidity_verifier -k target/vk -t evm -o "$OUT"

sed -i.bak -E \
  -e 's/^([[:space:]]*)assembly \{/\1assembly ("memory-safe") {/' \
  -e 's/^contract HonkVerifier is/contract ShieldedSpendVerifier is/' \
  -e '2a\
// Generated by tools/zk/build-circuit.sh from circuits/shielded_spend. Do not edit.
' \
  "$OUT"
rm -f "$OUT.bak"

echo "verifier written to $OUT"
echo "the fixture must be regenerated too: (cd $ROOT/tools && node zk/fixture.mjs)"
