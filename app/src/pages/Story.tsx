async function loadStory() {
  const demo = await getDemo();
  if (!demo) return null;
  const storyId = BigInt(demo.passports.story);
  const childId = BigInt(demo.passports.storyChild);
  const newId = BigInt(demo.passports.newBattery);
  const [parent, child, newBattery] = await Promise.all([getPassport(storyId), getPassport(childId), getPassport(newId)]);
  const [hParent, hChild, batchesP, batchesC] = await Promise.all([
    getHealthHistory(storyId), getHealthHistory(childId), getBatches({ passportId: storyId }), getBatches({ passportId: childId }),
  ]);
  const allBatches = [...batchesP, ...batchesC];
  const recent = allBatches.slice(-4).reverse();
  const recentTx = await Promise.all(recent.map((b) => getAnchorTx(b.tx)));
  const deviceKey = await getDeviceKey(parent.passport.deviceId);
  const model = parent.health.at ? await getModel(parent.health.modelId) : undefined;
  const impact = await getImpactTotals();
  const rep = impact.repurposed.find((r) => r.args.parentId === storyId);
  const ledger = await getLedgerBatch(BigInt(demo.batches.settled));
  const notes = await getNoteEvents();
  const shares = await getRecycledShares(newId);
  const spends = notes.spent.filter((s) => s.args.passportId === newId);
  const spendReceipt = spends.length ? await publicClient.getTransactionReceipt({ hash: spends[spends.length - 1].transactionHash }) : undefined;
  return {
    demo, storyId, childId, newId, parent, child, newBattery, health: [...hParent, ...hChild], allBatches,
    recent: recent.map((b, i) => ({ ...b, gas: recentTx[i].gasUsed, mldsa: recentTx[i].mldsaSigBytes, ecdsa: recentTx[i].ecdsaSigBytes })),
    deviceKey, model, rep, ledger, notes, shares, spends, spendGas: spendReceipt?.gasUsed,
  };
}
type StoryData = NonNullable<Awaited<ReturnType<typeof loadStory>>>;

function Chapter({ n, title, lead, children, last, split, visual }: { n: number; title: string; lead: string; children?: ReactNode; last?: boolean; split?: boolean; visual?: ReactNode }) {
  return (
    <section className="chapter reveal-static" aria-labelledby={`ch${n}`}>
      <div className="chapter__rail" aria-hidden="true">
        <div className="chapter__num">{n}</div>
        {!last && <div className="chapter__line" />}
      </div>
      <div className="chapter__body">
        {split ? (
          <div className="split" style={{ alignItems: "start" }}>
            <div className="stack-md">
              <div>
                <h3 id={`ch${n}`}>{title}</h3>
                <p className="t-small" style={{ marginTop: 10, fontSize: 16 }}>{lead}</p>
              </div>
              {children}
            </div>
            <div className="stage stage--soft">{visual}</div>
          </div>
        ) : (
          <div className="stack-md">
            <div>
              <h3 id={`ch${n}`}>{title}</h3>
              <p className="t-small" style={{ marginTop: 10, fontSize: 16, maxWidth: 680 }}>{lead}</p>
            </div>
            {children}
          </div>
        )}
      </div>
    </section>
  );
}

