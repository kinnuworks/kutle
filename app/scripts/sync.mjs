// Copies everything the app needs from the rest of the repository into app/:
//
//   contracts/out-app/<C>.sol/<C>.json   -> src/abi/<name>.ts   (typed `as const` ABIs for viem)
//   contracts/deployments/<chainId>.json -> src/config/deployments/<chainId>.json
//   circuits/shielded_spend/target/shielded_spend.json -> public/circuits/shielded_spend.json
//   tools/zk/{poseidon2,poseidon2-constants,notepool}.mjs -> src/vendor/zk/
//   tools/mldsa/prepare.mjs              -> src/vendor/mldsa/prepare.mjs
//   device/lib/{reading,merkle}.ts       -> src/vendor/device/
//
// The vendored files are committed so `pnpm build` works from a checkout of
// app/ alone. Run this again whenever the contracts, circuit or tools change.
//
//   node scripts/sync.mjs [--abi-only]

import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, "..");
const repo = resolve(app, "..");
const OUT = process.env.FOUNDRY_OUT_DIR ?? resolve(repo, "contracts/out-app");

// [file name in out-app, export name]
const CONTRACTS = [
  ["DeviceRegistry", "deviceRegistryAbi"],
  ["ReadingLog", "readingLogAbi"],
  ["PassportRegistry", "passportRegistryAbi"],
  ["ModelRegistry", "modelRegistryAbi"],
  ["ConservationLedger", "conservationLedgerAbi"],
  ["NotePool", "notePoolAbi"],
  ["KutleCouncil", "kutleCouncilAbi"],
  ["TimelockController", "timelockControllerAbi"],
  ["ShieldedSpendVerifier", "shieldedSpendVerifierAbi"],
  ["MLDSA44Verifier", "mldsa44VerifierAbi"],
  // Libraries: only their custom errors matter, for decoding reverts.
  ["MLDSAKey", "mldsaKeyAbi"],
  ["Conservation", "conservationAbi"],
  ["Elements", "elementsAbi"],
];

function artifactPath(name) {
  const dir = resolve(OUT, `${name}.sol`);
  const direct = resolve(dir, `${name}.json`);
  if (existsSync(direct)) return direct;
  if (existsSync(dir)) {
    const f = readdirSync(dir).find((x) => x.startsWith(name) && x.endsWith(".json"));
    if (f) return resolve(dir, f);
  }
  throw new Error(`no artifact for ${name} in ${OUT}; build with FOUNDRY_OUT=out-app first`);
}

function writeAbis() {
  const dir = resolve(app, "src/abi");
  mkdirSync(dir, { recursive: true });
  const index = [];
  for (const [name, exp] of CONTRACTS) {
    const j = JSON.parse(readFileSync(artifactPath(name), "utf8"));
    const body = `// Generated by scripts/sync.mjs from contracts/out-app/${name}.sol. Do not edit.\n` +
      `export const ${exp} = ${JSON.stringify(j.abi, null, 2)} as const;\n`;
    writeFileSync(resolve(dir, `${name}.ts`), body);
    index.push(`export { ${exp} } from "./${name}.ts";`);
  }
  writeFileSync(resolve(dir, "index.ts"), `// Generated by scripts/sync.mjs. Do not edit.\n${index.join("\n")}\n`);
  console.log(`abi: ${CONTRACTS.length} contracts -> src/abi`);
}

function copy(from, to) {
  const src = resolve(repo, from);
  if (!existsSync(src)) {
    console.warn(`skip ${from} (missing)`);
    return;
  }
  const dst = resolve(app, to);
  mkdirSync(dirname(dst), { recursive: true });
  copyFileSync(src, dst);
}

function copyDeployments() {
  const dir = resolve(repo, "contracts/deployments");
  if (!existsSync(dir)) return console.warn("no contracts/deployments yet");
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".json"))) {
    copy(`contracts/deployments/${f}`, `src/config/deployments/${f}`);
    console.log(`deployment ${f}`);
  }
}

writeAbis();
if (!process.argv.includes("--abi-only")) {
  copyDeployments();
  copy("circuits/shielded_spend/target/shielded_spend.json", "public/circuits/shielded_spend.json");
  for (const f of ["poseidon2.mjs", "poseidon2-constants.mjs", "notepool.mjs"]) copy(`tools/zk/${f}`, `src/vendor/zk/${f}`);
  copy("tools/mldsa/prepare.mjs", "src/vendor/mldsa/prepare.mjs");
  for (const f of ["reading.ts", "merkle.ts"]) copy(`device/lib/${f}`, `src/vendor/device/${f}`);
  console.log("vendored circuit, zk, mldsa and device files");
}
